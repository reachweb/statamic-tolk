<?php

namespace Reach\StatamicTolk\Console\Concerns;

use Illuminate\Support\Str;
use Reach\StatamicTolk\Contracts\Target;
use Reach\StatamicTolk\Enums\FieldStatus;
use Reach\StatamicTolk\Enums\TargetResultStatus;
use Reach\StatamicTolk\Translation\Plan;
use Reach\StatamicTolk\Translation\TargetResult;
use Statamic\Facades\Site;
use Symfony\Component\Console\Formatter\OutputFormatter;

/**
 * The output of commands that translate targets one by one: a line per target, then a summary and the fields that were
 * not translated, with the reason.
 */
trait ReportsTranslations
{
    private const array OUT_OF_SCOPE_REASONS = [
        'auto_title' => 'title generated by the collection',
        'unsupported_fieldtype' => 'unsupported fieldtype',
        'computed' => 'computed field',
        'hidden' => 'hidden field',
        'disabled' => 'translation turned off for the field',
        'excluded' => 'excluded in the settings',
        'not_localizable' => 'not localizable',
    ];

    /** @var list<array{label: string, result: TargetResult}> */
    private array $results = [];

    /** @var array<string, array{field: string, type: string, reason: string}> */
    private array $outOfScope = [];

    private bool $reviews = false;

    /**
     * Forgets the previous report: one command instance serves every call in a process (Artisan::call(), the scheduler).
     *
     * @param  bool  $reviews  whether the operation reviews, so the lines and the summary count corrections
     */
    protected function startReport(bool $reviews = false): void
    {
        $this->results = [];
        $this->outOfScope = [];
        $this->reviews = $reviews;
    }

    protected function targetLabel(Target $target): string
    {
        return $target->title().' → '.(Site::get($target->targetSite())?->name() ?? $target->targetSite());
    }

    /**
     * Notes the target's top-level fields that are never translated. The slug is left out: it is never translated by
     * design (D16).
     */
    protected function noteOutOfScope(Target $target): void
    {
        foreach ($target->explainFields() as $field) {
            if (! $field['in_scope'] && $field['reason'] !== 'slug') {
                $name = $target->container().'.'.$field['handle'];
                $this->outOfScope[$name.':'.$field['reason']] ??= [
                    'field' => $name,
                    'type' => $field['type'],
                    'reason' => $field['reason'],
                ];
            }
        }
    }

    protected function startTarget(string $label): void
    {
        $this->output->write("  {$label}: ");
    }

    protected function reportResult(string $label, TargetResult $result): void
    {
        $this->results[] = ['label' => $label, 'result' => $result];
        $this->output->writeln($this->describeResult($result));

        foreach ($result->warnings as $warning) {
            $this->output->writeln("    <comment>{$warning}</comment>");
        }

        if ($this->output->isVerbose()) {
            foreach ($result->corrections as $handle => $corrections) {
                foreach ($corrections as $correction) {
                    $this->output->writeln(OutputFormatter::escape(sprintf(
                        '    %s: "%s" → "%s" (%s)',
                        $handle,
                        $correction['before'],
                        $correction['after'],
                        $correction['reason'],
                    )));
                }
            }
        }
    }

    protected function reportPlan(Plan $plan): void
    {
        if ($plan->isEmpty()) {
            $this->output->writeln('<comment>nothing to do</comment>');

            return;
        }

        $size = $this->planSize($plan);

        $this->output->writeln(implode(', ', $plan->fieldHandles())
            .' ('.$this->count($size['segments'], 'segment').', '.$this->count($size['characters'], 'character')
            .($size['reused'] > 0 ? ', '.$this->count($size['reused'], 'segment').' reused' : '').')');
    }

    /**
     * @return array{segments: int, characters: int, reused: int} what the plan sends to the model, and what it reuses
     */
    protected function planSize(Plan $plan): array
    {
        return [
            'segments' => array_sum(array_map(fn (array $batch) => count($batch['segment_ids']), $plan->batches)),
            'characters' => array_sum(array_column($plan->batches, 'chars')),
            'reused' => array_sum(array_column($plan->fields, 'reused')),
        ];
    }

    /**
     * @return array{done: int, skipped: int, failed: int} a target reviewed without corrections counts as done
     */
    protected function resultCounts(): array
    {
        $counts = ['done' => 0, 'skipped' => 0, 'failed' => 0];

        foreach ($this->results as ['result' => $result]) {
            $counts[$result->reason === TargetResult::NO_CORRECTIONS ? 'done' : $result->status->value]++;
        }

        return $counts;
    }

    /**
     * @return int the number of targets that were saved
     */
    protected function savedCount(): int
    {
        return count(array_filter($this->results, fn (array $row) => $row['result']->status === TargetResultStatus::Done));
    }

    protected function summarize(): void
    {
        $incomplete = [];
        $incompleteFields = 0;

        foreach ($this->results as ['label' => $label, 'result' => $result]) {
            if ($fields = $this->fieldsWith($result, TargetResult::INCOMPLETE)) {
                $incomplete[] = [$label, implode(', ', $fields)];
                $incompleteFields += count($fields);
            }
        }

        $corrections = array_sum(array_map(fn (array $row) => $this->correctionCount($row['result']), $this->results));

        $this->newLine();
        $this->table(
            ['Done', 'Skipped', 'Failed', 'Fields left incomplete', ...($this->reviews ? ['Corrections'] : [])],
            [[...array_values($this->resultCounts()), $incompleteFields, ...($this->reviews ? [$corrections] : [])]],
        );

        if ($corrections > 0 && ! $this->output->isVerbose()) {
            $this->line('Run the command with -v to see each correction and its reason.');
        }

        if ($incomplete !== []) {
            $this->line('Parts of these fields could not be translated and are still in the source language. The next update retries them.');
            $this->table(['Target', 'Fields'], $incomplete);
        }

        $this->summarizeOutOfScope();
    }

    protected function summarizeOutOfScope(): void
    {
        if ($this->outOfScope === []) {
            return;
        }

        $this->newLine();
        $this->line('These fields are not translated:');
        $this->table(['Field', 'Fieldtype', 'Reason'], array_map(fn (array $row) => [
            $row['field'],
            $row['type'],
            self::OUT_OF_SCOPE_REASONS[$row['reason']] ?? str_replace('_', ' ', $row['reason']),
        ], array_values($this->outOfScope)));

        if (in_array('not_localizable', array_column($this->outOfScope, 'reason'), true)) {
            $this->line('A field that is not localizable is shared by every site. Make it localizable in its blueprint to translate it.');
        }
    }

    private function describeResult(TargetResult $result): string
    {
        $applied = $result->appliedFields();

        $description = match (true) {
            $result->status === TargetResultStatus::Done => '<info>done</info>, '.($result->created ? 'created, ' : '').$this->count(count($applied), 'field').$this->correctionsNote($result),
            $result->reason === TargetResult::NO_CORRECTIONS => '<info>reviewed</info>, nothing to correct',
            $result->status === TargetResultStatus::Skipped => '<comment>skipped</comment>, '.match ($result->reason) {
                TargetResult::NOTHING_TO_DO => 'nothing to do',
                TargetResult::TARGET_CHANGED => 'edited by someone while it was being translated',
                default => str_replace('_', ' ', (string) $result->reason),
            },
            default => '<fg=red>failed</>, '.$result->error,
        };

        $details = array_filter([
            'left incomplete' => $this->fieldsWith($result, TargetResult::INCOMPLETE),
            'manual edits kept' => $this->fieldsWith($result, FieldStatus::Manual->value),
            'edited meanwhile, kept' => $this->fieldsWith($result, TargetResult::TARGET_CHANGED),
        ]);

        foreach ($details as $what => $fields) {
            $description .= "; {$what}: ".implode(', ', $fields);
        }

        return $description;
    }

    private function correctionsNote(TargetResult $result): string
    {
        if (! $this->reviews) {
            return '';
        }

        $count = $this->correctionCount($result);

        return ', '.($count > 0 ? $this->count($count, 'correction') : 'no corrections');
    }

    private function correctionCount(TargetResult $result): int
    {
        return array_sum(array_map('count', $result->corrections));
    }

    /**
     * @return list<string>
     */
    private function fieldsWith(TargetResult $result, string $outcome): array
    {
        return array_keys($result->fields, $outcome, true);
    }

    private function count(int $count, string $noun): string
    {
        return number_format($count).' '.Str::plural($noun, $count);
    }
}
